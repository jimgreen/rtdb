async(page)=>{
  const checks=[],errors=[];const check=(ok,name)=>{if(!ok)throw Error(name);checks.push(name);};
  page.on('pageerror',error=>errors.push(error.message));
  if(await page.locator('#confirm-dialog').isVisible())await page.locator('#confirm-dialog').getByRole('button',{name:'取消',exact:true}).click();
  if(await page.locator('#storage-maintenance-dialog').isVisible())await page.locator('#storage-close').click();
  check(await page.evaluate(()=>state.dataDir.includes('storage-lab-')),'isolated lab only');
  const menu=page.getByRole('menuitem',{name:'存储维护',exact:true});
  if(!await menu.isVisible())await page.getByLabel('表索引，右键打开操作菜单').click({button:'right'});
  await menu.click();
  const dialog=page.getByRole('dialog',{name:'存储维护',exact:true});
  await dialog.waitFor();await page.waitForFunction(()=>!storageMaintenance.busy&&storageMaintenance.preview);
  check(await page.locator('#storage-statistics>div').count()===4,'four storage categories shown without selecting database');
  const initial=await page.locator('#storage-candidates tbody tr').count();check(initial>=3,'expired candidates listed');
  const upload=dialog.getByLabel('上传暂存保留天数');
  await upload.fill('2');check(!await page.locator('#storage-clean').isEnabled(),'unsaved policy disables cleanup');
  await page.getByRole('button',{name:'保存配置',exact:true}).click();
  await page.waitForFunction(()=>!storageMaintenance.busy&&storageMaintenance.preview?.config.upload_retention_days===2);
  check(await page.locator('#storage-candidates tbody tr').count()===initial,'saving configuration does not clean');
  await page.setViewportSize({width:430,height:850});
  const fit=await dialog.evaluate(d=>({w:d.clientWidth,scroll:d.scrollWidth,rect:d.getBoundingClientRect().toJSON()}));
  check(fit.scroll<=fit.w+1&&fit.rect.left>=0&&fit.rect.right<=430,'dialog fits narrow viewport without horizontal overflow');
  await page.screenshot({path:'D:/codex/rtdb/output/playwright/storage-narrow.png'});
  await page.setViewportSize({width:1280,height:900});
  await page.locator('#storage-clean').click();
  await page.locator('#confirm-dialog').waitFor();
  await page.locator('#confirm-dialog').getByRole('button',{name:'取消',exact:true}).click();
  await page.waitForFunction(()=>!storageMaintenance.busy);
  check(await page.locator('#storage-candidates tbody tr').count()===initial,'cancel leaves every candidate intact');
  await page.screenshot({path:'D:/codex/rtdb/output/playwright/storage-before.png'});
  await page.locator('#storage-clean').click();
  await page.locator('#confirm-action').click();
  await page.waitForFunction(()=>!storageMaintenance.busy&&document.getElementById('storage-status').textContent.startsWith('已处理'));
  check(await page.locator('#storage-candidates tbody tr').count()===0,'confirmed background cleanup removes old candidates');
  check(!await page.locator('#storage-clean').isEnabled(),'empty cleanup disabled');
  const rows=await page.request.get(new URL('/api/manage/tables/nodes/rows?database=storage_lab.sqlite3',page.url()).href);
  const data=await rows.json();check(data.total===1||data.count===1||data.rows?.length===1,'business record survives cleanup');
  const recent=await (await page.request.get(new URL('/api/manage/tasks',page.url()).href)).json();
  check(recent.tasks.some(t=>t.path==='storage-maintenance'&&t.status==='done'),'cleanup task persisted');
  await page.screenshot({path:'D:/codex/rtdb/output/playwright/storage-after.png'});
  check(errors.length===0,'no JavaScript errors');
  return {checks,status:await page.locator('#storage-status').innerText(),errors};
}
