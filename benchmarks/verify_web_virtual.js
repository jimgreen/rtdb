// Only against benchmarks/serve_web_render_lab.py.
async(page)=>{
  const checks=[],errors=[],origin=new URL(page.url()).origin;
  page.on('pageerror',e=>errors.push(e.message));
  const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
  const idle=()=>page.waitForFunction(()=>!state.busy&&state.databases.length);
  const cell=(row,field)=>page.locator(`#data-grid td[data-cell-row="${row}"][data-cell-field="${field}"]`);
  await page.goto(origin);await idle();
  check(await page.evaluate(()=>state.dataDir.includes('browser-render-lab')),'isolated fixture verified');
  await page.locator('#database-select').selectOption('lab.db');await idle();
  await page.locator('#page-size').selectOption('500');await idle();
  check(await page.evaluate(()=>virtualGrid.active&&state.records.length===500),'500 x 40 page uses virtual rendering');
  check(await page.locator('#data-grid td.value').count()<2000,'mounted cells bounded by viewport');
  const start=await cell(0,'v01').boundingBox(),viewport=await page.locator('#data-grid').boundingBox();
  await page.mouse.move(start.x+20,start.y+start.height/2);await page.mouse.down();
  await page.mouse.move(start.x+20,viewport.y+viewport.height-8,{steps:5});
  await page.waitForFunction(()=>el('data-grid').scrollTop>400);await page.mouse.up();
  check(await page.evaluate(()=>Math.max(...[...state.selectedCells].map(key=>splitCellSelectionKey(key).index))>15),'mouse drag continues selection while viewport auto-scrolls');
  check(await page.evaluate(()=>state.chartSeries.length===0),'drag selection does not create curves');
  check(await page.evaluate(()=>{const rows=structuredClone(state.records);rows[499].row.v39=1500.39;rows[499].ref.version='virtual-test-version';return patchGridRecords(rows); }),'partial refresh updates model with offscreen rows');
  await page.evaluate(()=>virtualGrid.ensure(499,39));
  check(await cell(499,'v39').innerText()==='1500.39','offscreen update appears when row mounts');
  await page.evaluate(()=>queryRows());await idle();await page.evaluate(()=>virtualGrid.ensure(499,39));
  check(await cell(499,'v39').innerText()==='500.39','last row and column render correct data');
  check(await cell(499,'id').isVisible(),'key stays visible at far right');
  const left=await cell(499,'id').evaluate(el=>el.getBoundingClientRect().left);
  const edge=await page.locator('#data-grid').evaluate(el=>el.getBoundingClientRect().left);
  check(Math.abs(left-edge-36)<3,'key position remains frozen');
  await cell(499,'v39').click();await page.keyboard.press('Control+Home');
  check(await cell(0,'id').evaluate(el=>document.activeElement===el),'Ctrl Home materializes first cell');
  await page.keyboard.press('Control+End');
  check(await cell(499,'v39').evaluate(el=>document.activeElement===el),'Ctrl End materializes last cell');
  await page.evaluate(()=>selectGridCells(10,8,450,9));
  const copied=await page.evaluate(()=>parseClipboardMatrix(gridSelectionClipboardText(gridSelectionModel())));
  check(copied.length===441&&copied.every(r=>r.length===2),'copy includes offscreen selected cells');
  await page.evaluate(()=>{selectGridCells(100,8,102,9);virtualGrid.ensure(100,8);});
  await cell(100,'v08').click({button:'right'});await page.locator('[data-action="chart-left"]').click();
  check(await page.evaluate(()=>state.chartSeries.length===2),'selected curves added only by context action');
  await page.evaluate(()=>pasteClipboardText('801.5\t901.5\n802.5\t902.5\n803.5\t903.5'));
  check(await page.evaluate(()=>state.records[102].row.v09===903.5&&state.pendingEdits.size===6),'paste modifies complete selected model');
  await page.evaluate(()=>virtualGrid.ensure(499,39));await page.evaluate(()=>virtualGrid.ensure(102,9));
  check(await cell(102,'v09').evaluate(el=>el.classList.contains('cell-modified')),'modified highlight survives unmount and remount');
  check(await page.evaluate(()=>buildChartModel().series[1].points[2].value===903.5),'curve follows remounted cell edits');
  await page.evaluate(()=>restoreEdit());
  check(await page.evaluate(()=>state.pendingEdits.size===0&&state.records[102].row.v09===103.09),'undo restores offscreen edits');
  await page.evaluate(()=>restoreEdit(true));
  check(await page.evaluate(()=>state.pendingEdits.size===6),'redo restores selected edits');
  await page.evaluate(()=>locateEdit(state.records[101],'v09'));
  check(await cell(101,'v09').evaluate(el=>document.activeElement===el),'error locator materializes exact cell');
  await cell(101,'v09').dblclick();await cell(101,'v09').locator('input').fill('777.25');await cell(101,'v09').locator('input').press('Enter');
  check(await page.evaluate(()=>state.records[101].row.v09===777.25),'double click edits correct virtual row');
  await page.evaluate(()=>{while(editUndo.length)restoreEdit();});
  await page.evaluate(()=>virtualGrid.ensure(0,0));await cell(0,'id').dblclick();
  check(await cell(0,'id').locator('input').count()===0,'existing key remains read only');
  await page.screenshot({path:'output/playwright/virtual-grid.png'});
  check(errors.length===0,'no browser exceptions');return {passed:checks.length,checks,errors,mounted:await page.locator('#data-grid td.value').count()};
}
